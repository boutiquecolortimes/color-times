export type IconName = keyof typeof ICONS;

interface Props {
  name: IconName | string;
  size?: number;
  color?: string;
  strokeWidth?: number;
  fill?: string;
}

export function Icon({ name, size = 20, color = colors.text, strokeWidth = 1.6, fill }: Props) {
  const Component = ICONS[name as IconName];
  if (!Component) return null;
  return <Component size={size} color={color} strokeWidth={strokeWidth} fill={fill ?? 'none'} />;
}
